import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';

const dist = process.argv[2] || '.next';
const output = process.argv[3] || 'public/sw.js';
const buildId = (await readFile(join(dist, 'BUILD_ID'), 'utf8')).trim();
const staticRoot = join(dist, 'static');

async function files(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? files(path) : [path];
  }));
  return nested.flat();
}

const staticAssets = (await files(staticRoot))
  .filter((path) => /\.(?:js|css|woff2?|png|svg)$/.test(path))
  .map((path) => `/_next/static/${relative(staticRoot, path).split(sep).join('/')}`);
const downloadsHtml = await readFile(join(dist, 'server', 'app', 'downloads.html'), 'utf8');
const coreStaticAssets = [...new Set(downloadsHtml.match(/\/_next\/static\/[^"'\\\s<>]+/g) || [])]
  .filter((url) => /\.(?:js|css)$/.test(url) && staticAssets.includes(url));
if (coreStaticAssets.length === 0) throw new Error('Could not find the Downloads route assets.');

const shellAssets = [
  '/downloads', '/manifest.webmanifest', '/icon.svg', '/icon-192.png', '/icon-512.png',
  ...staticAssets,
];
const requiredAssets = ['/downloads', ...coreStaticAssets];
const optionalAssets = shellAssets.filter((url) => !requiredAssets.includes(url));

const worker = `/* Generated by scripts/build-offline-worker.mjs for Next build ${buildId}. */
const CACHE = ${JSON.stringify(`mdmedia-app-${buildId}`)};
const SHELL = ${JSON.stringify(shellAssets)};
const REQUIRED = ${JSON.stringify(requiredAssets)};
const OPTIONAL = ${JSON.stringify(optionalAssets)};
const STATIC = new Set(SHELL.filter((url) => url.startsWith('/_next/static/')));

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    await cache.addAll(REQUIRED);
    await Promise.allSettled(OPTIONAL.map(async (url) => {
      const response = await fetch(url);
      if (response.ok) await cache.put(url, response);
    }));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if ((name.startsWith('mdmedia-app-') || name.startsWith('mdmedia-offline-')) && name !== CACHE) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (url.pathname.startsWith('/api/') || url.searchParams.has('_rsc')) return;

  if (url.pathname === '/offline.html' && request.mode === 'navigate') {
    event.respondWith(Response.redirect('/downloads', 302));
    return;
  }

  if (STATIC.has(url.pathname) || SHELL.includes(url.pathname) && request.mode !== 'navigate') {
    event.respondWith((async () => (await caches.match(url.pathname)) || fetch(request))());
    return;
  }

  if (request.mode === 'navigate') {
    event.respondWith((async () => {
      try {
        const response = await fetch(request);
        if (response.ok) {
          if (url.pathname === '/downloads') {
            const cache = await caches.open(CACHE);
            await cache.put('/downloads', response.clone());
          }
          return response;
        }
        if (response.status < 500) return response;
      } catch { /* Studio server is unavailable. */ }
      if (url.pathname === '/downloads') return (await caches.match('/downloads')) || Response.error();
      return Response.redirect('/downloads', 302);
    })());
  }
});
`;

await writeFile(output, worker);
console.log(`Offline worker: ${requiredAssets.length} required and ${optionalAssets.length} optional assets for build ${buildId}`);
