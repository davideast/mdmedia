/**
 * `mdmedia character`: characters as versioned files (docs/characters.md).
 * `new`, `show`, `list`, `measure` (reference levels from approved lines),
 * `still` (a reference still from a take, with where it came from) and
 * `swap` (a take's on-camera speech in a character's voice).
 */

const today = () => new Date().toISOString().slice(0, 10);

function shown(file: string): string {
  const relative = path.relative(process.cwd(), file);
  return relative && !relative.startsWith('..') ? relative : file;
}

async function guard(name: string, run: () => Promise<void>): Promise<void> {
  try {
    await run();
  } catch (error) {
    console.error(`mdmedia character ${name}: ${error instanceof Error ? error.message : String(error)}`);
    process.exitCode = 1;
  }
}

const dirArg = { type: 'string', description: 'The characters folder (default MDMEDIA_CHARACTERS_DIR, else docs/characters in this repository)' } as const;

/** A character's summary, as `show` prints it. */
export function formatCharacter(character: Character, versions: number[] = [character.version]): string {
  const out = [
    `${character.name} — ${formatCharacterRef(character)}${versions.length > 1 ? ` (versions ${versions.join(', ')})` : ''}`,
    character.description,
    '',
    `Look: ${character.look.description}`,
    ...(character.look.never.length ? [`  never: ${character.look.never.join('; ')}`] : []),
    `Voice: ${describeVoice(character.voice)}${character.voice.settings ? ` ${JSON.stringify(character.voice.settings)}` : ''}`,
    ...(character.voice.notes ? [`  ${character.voice.notes}`] : []),
    `Delivery: ${character.delivery.register}`,
    ...(character.delivery.never.length ? [`  never: ${character.delivery.never.join('; ')}`] : []),
  ];
  const ref = character.delivery.reference;
  if (ref) {
    out.push(`  reference: ${describeLevels(ref.levels)}`);
    out.push(`  typical: ${[ref.typical.loudness !== null ? `${ref.typical.loudness} LUFS` : null, ref.typical.pitch !== null ? `${ref.typical.pitch} Hz` : null, ref.typical.pitchRange !== null ? `${ref.typical.pitchRange} st range` : null, ref.typical.rate !== null ? `${ref.typical.rate} words/s` : null].filter(Boolean).join(', ')}`);
    out.push(`  from ${ref.lines.length} approved line${ref.lines.length === 1 ? '' : 's'}${ref.levels.source ? ` (${ref.levels.source})` : ''}, measured ${ref.measuredAt.slice(0, 10)}:`);
    for (const l of ref.lines) {
      out.push(`    ${l.cut}#${l.line}  ${l.loudness ?? '–'} LUFS  ${l.pitch ?? '–'} Hz  ${l.pitchRange ?? '–'} st  ${l.rate ?? '–'} w/s`);
    }
  } else {
    out.push('  reference: not measured yet (mdmedia character measure)');
  }
  out.push(`Stills: ${character.stills.length === 0 ? 'none yet (mdmedia character still)' : ''}`);
  for (const s of character.stills) {
    const from = 'take' in s.from ? `${s.from.take} at ${s.from.at} s` : `generated by ${s.from.generated.provider}${s.from.generated.ref ? ` from ${s.from.generated.ref}` : ''}`;
    out.push(`  ${s.id}: ${s.file} (${from})${s.note ? `, ${s.note}` : ''}`);
  }
  out.push('Changelog:', ...character.changelog.map((c) => `  v${c.version} ${c.date}: ${c.changes}`));
  return out.join('\n');
}

const create = defineCommand({
  meta: { name: 'new', description: 'Start a character at version 1, to fill in: name, description, look, voice and delivery' },
  args: {
    id: { type: 'positional', required: true, description: 'Its id: lowercase words joined by hyphens, like big-hal' },
    name: { type: 'string', required: true, description: 'Its name, as cut lines give the speaker: "Big Hal"' },
    description: { type: 'string', description: 'Who they are, in a sentence' },
    kind: { type: 'string', default: 'person', description: 'person or thing' },
    voice: { type: 'string', description: 'An ElevenLabs voice name for text-to-speech and swaps ("Eric"); default the video model\'s own voice' },
    root: { type: 'string', description: 'The media root its stills go under (default MDMEDIA_CUT_MEDIA_ROOT)' },
    dir: dirArg,
  },
  async run({ args }) {
    await guard('new', async () => {
      const dir = charactersDir({ dir: args.dir });
      const root = args.root ?? process.env.MDMEDIA_CUT_MEDIA_ROOT;
      if (!root) throw new Error('Pass --root, the media root its stills go under (or set MDMEDIA_CUT_MEDIA_ROOT).');
      if (args.kind !== 'person' && args.kind !== 'thing') throw new Error('--kind must be person or thing.');
      const voice: CharacterVoice | undefined = args.voice ? { provider: 'elevenlabs', name: args.voice, uses: ['tts', 'swap'] } : undefined;
      await mkdir(dir, { recursive: true });
      const character = newCharacter({ id: args.id, name: args.name, description: args.description, kind: args.kind, root, voice, date: today() });
      const file = await writeCharacter(dir, character, { create: true });
      console.log(`Wrote ${shown(file)} (${formatCharacterRef(character)}). Fill in its look, delivery and "never" rules, then add stills and measure it.`);
    });
  },
});

const show = defineCommand({
  meta: { name: 'show', description: 'Show a character (id, or id@version)' },
  args: {
    ref: { type: 'positional', required: true, description: 'big-hal, or big-hal@1' },
    json: { type: 'boolean', default: false, description: 'Print the character file' },
    dir: dirArg,
  },
  async run({ args }) {
    await guard('show', async () => {
      const dir = charactersDir({ dir: args.dir });
      const { character } = await loadCharacter(dir, args.ref);
      if (args.json) {
        console.log(JSON.stringify(character, null, 2));
        return;
      }
      const versions = (await listCharacters(dir)).find((c) => c.character.id === character.id)?.versions;
      console.log(formatCharacter(character, versions));
    });
  },
});

const list = defineCommand({
  meta: { name: 'list', description: 'List the characters, each at its current version' },
  args: { json: { type: 'boolean', default: false, description: 'Print JSON' }, dir: dirArg },
  async run({ args }) {
    await guard('list', async () => {
      const all = await listCharacters(charactersDir({ dir: args.dir }));
      if (args.json) {
        console.log(JSON.stringify(all.map((c) => ({ ref: formatCharacterRef(c.character), name: c.character.name, versions: c.versions, voice: c.character.voice, reference: c.character.delivery.reference?.levels ?? null })), null, 2));
        return;
      }
      if (all.length === 0) {
        console.log('No characters yet (mdmedia character new).');
        return;
      }
      const rows = [['character', 'name', 'voice', 'reference'], ...all.map((c) => [
        formatCharacterRef(c.character),
        c.character.name,
        describeVoice(c.character.voice),
        c.character.delivery.reference ? `${c.character.delivery.reference.lines.length} lines` : 'not measured',
      ])];
      const widths = rows[0]!.map((_, i) => Math.max(...rows.map((r) => r[i]!.length)));
      for (const r of rows) console.log(r.map((cell, i) => cell.padEnd(widths[i]!)).join('  ').trimEnd());
    });
  },
});

const measure = defineCommand({
  meta: {
    name: 'measure',
    description: "Measure a character's reference levels (loudness, pitch, pace) from named approved cut lines: measure big-hal docs/cuts/big-hal-take7.cut.json#howdy,thisone …",
  },
  args: {
    id: { type: 'positional', required: true, description: 'The character' },
    lines: { type: 'positional', required: true, description: 'A cut and its approved line ids, cut.json#a,b (more may follow)' },
    source: { type: 'string', required: true, description: 'Where the lines are from, quoted in every flag: "approved lines in Night Wagon Take 9"' },
    bump: { type: 'boolean', default: false, description: 'Write the levels as a new version, keeping the current one as <id>@<n>.character.json' },
    force: { type: 'boolean', default: false, description: 'Replace levels the current version already has (only before a production uses it)' },
    'dry-run': { type: 'boolean', default: false, description: 'Print the levels without writing them' },
    root: { type: 'string', description: "Media root for the cuts (default MDMEDIA_CUT_MEDIA_ROOT, else each cut's media.root)" },
    dir: dirArg,
  },
  async run({ args }) {
    await guard('measure', async () => {
      const dir = charactersDir({ dir: args.dir });
      const { character } = await loadCharacter(dir, args.id);
      if (parseCharacterRef(args.id)) throw new Error('Measure the current version: pass the id alone.');
      const selections = [args.lines, ...args._.slice(2)].map(parseLineSelection);
      const measured = await measureLines(selections, {
        name: character.name,
        root: cutMediaRootArg(args.root),
        onStep: process.stderr.isTTY ? (m) => process.stderr.write(`${m}\n`) : undefined,
      });
      for (const o of measured.otherSpeakers) console.error(`warning: ${o.cut}#${o.line} is spoken by "${o.speaker}", not "${character.name}"`);
      for (const u of measured.untimed) console.error(`warning: ${u.cut}#${u.line} has no word timings, so it has no rate (run mdmedia cut words)`);
      const reference = referenceFromLines(measured.lines, { source: args.source, method: MEASURE_METHOD, measuredAt: new Date().toISOString() });
      const summary = `Reference levels measured from ${measured.lines.length} approved line${measured.lines.length === 1 ? '' : 's'} (${args.source}): ${describeLevels(reference.levels)}.`;
      if (args['dry-run']) {
        console.log(formatCharacter({ ...character, delivery: { ...character.delivery, reference } }));
        return;
      }
      if (args.bump) {
        const next = nextVersion({ ...character, delivery: { ...character.delivery, reference } }, summary, today());
        const { file, archived } = await writeNewVersion(dir, next);
        console.log(`${summary}\nWrote ${shown(file)} (${formatCharacterRef(next)}); kept ${shown(archived)}.`);
        return;
      }
      if (character.delivery.reference && !args.force) {
        throw new Error(`${formatCharacterRef(character)} has reference levels already. Pass --bump for a new version (a production made with ${formatCharacterRef(character)} keeps its levels), or --force to replace them if no production uses it yet.`);
      }
      const changelog = character.changelog.map((c) => (c.version === character.version ? { ...c, changes: `${c.changes.replace(/\s*Reference levels measured from[^]*$/, '')} ${summary}`.trim() } : c));
      const file = await writeCharacter(dir, { ...character, delivery: { ...character.delivery, reference }, changelog });
      console.log(`${summary}\nWrote ${shown(file)} (${formatCharacterRef(character)}).`);
    });
  },
});

const still = defineCommand({
  meta: { name: 'still', description: "Save a frame of a take as one of a character's reference stills, recording which take and when" },
  args: {
    id: { type: 'positional', required: true, description: 'The character' },
    take: { type: 'positional', required: true, description: 'A take name (takes/<name>.mp4 under the media root) or a video file' },
    at: { type: 'positional', required: true, description: 'Seconds into the take' },
    as: { type: 'string', required: true, description: 'The still\'s id: "front", "three-quarter"' },
    note: { type: 'string', description: 'What it shows' },
    dir: dirArg,
  },
  async run({ args }) {
    await guard('still', async () => {
      const dir = charactersDir({ dir: args.dir });
      const { character } = await loadCharacter(dir, args.id);
      const at = Number(args.at);
      if (!Number.isFinite(at) || at < 0) throw new Error('The time must be seconds, 0 or more.');
      if (character.stills.some((s) => s.id === args.as)) throw new Error(`${character.id} has a still "${args.as}" already.`);
      const root = characterRoot(character);
      const isFile = /\.(mp4|mov|webm)$/i.test(args.take);
      const video = isFile ? path.resolve(args.take) : path.join(root, 'takes', `${args.take}.mp4`);
      if (!existsSync(video)) throw new Error(`No video at ${video}.`);
      const take = isFile ? path.relative(root, video).split(path.sep).join('/') : args.take;
      const rel = `characters/${character.id}/${args.as}.png`;
      const out = path.join(root, rel);
      if (existsSync(out)) throw new Error(`${out} exists; choose another id.`);
      await mkdir(path.dirname(out), { recursive: true });
      await runFfmpeg(['-hide_banner', '-loglevel', 'error', '-nostdin', '-n', '-ss', at.toFixed(3), '-i', video, '-frames:v', '1', out], { ffmpeg: await findFfmpeg(), what: 'saving the still' });
      const next = { ...character, stills: [...character.stills, { id: args.as, file: rel, from: { take, at }, ...(args.note ? { note: args.note } : {}) }] };
      const file = await writeCharacter(dir, next);
      console.log(`Saved ${out}\nWrote ${shown(file)} (${formatCharacterRef(character)}).`);
    });
  },
});

/** The voice to swap to: a character's (its voice and settings), else an ElevenLabs voice name or id. */
async function swapTarget(voice: string, dir: string, catalog: ElevenLabsVoiceCatalog): Promise<{ id: string; name: string; settings: SpeechToSpeechSettings; character: string | null }> {
  const isCharacter = parseCharacterRef(voice) !== null || existsSync(path.join(dir, `${voice}.character.json`));
  if (isCharacter) {
    const { character } = await loadCharacter(dir, voice);
    const v = character.voice;
    if (v.provider !== 'elevenlabs' || !v.uses.includes('swap')) throw new Error(`${formatCharacterRef(character)} has no voice to swap to (${describeVoice(v)}).`);
    const id = v.id ?? (await catalog.resolve(v.name!));
    const settings: SpeechToSpeechSettings = {};
    for (const key of ['stability', 'similarity_boost', 'style', 'speed'] as const) if (typeof v.settings?.[key] === 'number') settings[key] = v.settings[key] as number;
    if (typeof v.settings?.use_speaker_boost === 'boolean') settings.use_speaker_boost = v.settings.use_speaker_boost;
    return { id, name: v.name ?? id, settings, character: formatCharacterRef(character) };
  }
  const id = await catalog.resolve(voice);
  return { id, name: voice, settings: {}, character: null };
}

/** The swap's comparison, in a few lines. */
export function formatSwap(report: SwapReport): string {
  const out = [`${shown(report.out)}: ${shown(report.video)} in ${report.voice.name}'s voice (${report.model}${report.removeBackgroundNoise ? ', background removed' : ''})`];
  const c = report.comparison;
  if (!c) return [...out, '(pass --text to align and compare the words before and after)'].join('\n');
  const n = (x: number | null, unit: string, digits = 1) => (x === null ? '–' : `${x > 0 ? '+' : ''}${x.toFixed(digits)}${unit}`);
  out.push(
    `words: ${c.sameWords ? `the same ${c.words.length}` : 'DIFFERENT'}; word starts move ${n(c.drift.median, ' s', 3)} (median), at most ${n(c.drift.largest, ' s', 3)}${c.drift.word ? ` on "${c.drift.word}"` : ''}`,
    `envelope: best lag ${n(c.envelope.lag, ' s', 3)} (correlation ${c.envelope.correlation.toFixed(2)})`,
    `before: ${c.before.loudness ?? '–'} LUFS, ${c.before.pitch?.median ?? '–'} Hz, range ${c.before.pitch?.range ?? '–'} st, ${c.before.rate ?? '–'} words/s, speech ${c.before.speech.start}–${c.before.speech.end} s`,
    `after:  ${c.after.loudness ?? '–'} LUFS, ${c.after.pitch?.median ?? '–'} Hz, range ${c.after.pitch?.range ?? '–'} st, ${c.after.rate ?? '–'} words/s, speech ${c.after.speech.start}–${c.after.speech.end} s`,
    `change: ${n(c.change.loudness, ' LU')}, pitch ${n(c.change.pitch, ' st')}, range ${n(c.change.pitchRange, ' st')}, pace ${n(c.change.rate, ' words/s', 2)}, length ${n(c.change.length, ' s', 3)}`,
  );
  return out.join('\n');
}

const swap = defineCommand({
  meta: {
    name: 'swap',
    description: "Put a take's on-camera speech into a character's voice (ElevenLabs speech-to-speech), keeping its timing and lip sync; writes the new take and a before/after report",
  },
  args: {
    video: { type: 'positional', required: true, description: 'The take' },
    voice: { type: 'positional', required: true, description: 'A character (chet, chet@1) or an ElevenLabs voice name or id' },
    out: { type: 'string', required: true, description: 'The new take (never overwritten); <name>.before.wav, .after.wav and .swap.json go beside it' },
    text: { type: 'string', description: 'The words spoken, to align before and after and measure drift, loudness, pitch and pace' },
    model: { type: 'string', description: 'The speech-to-speech model (default eleven_english_sts_v2)' },
    'keep-noise': { type: 'boolean', default: false, description: "Send the take's sound as it is, without ElevenLabs' background removal" },
    seed: { type: 'string', description: 'A seed, for a repeatable conversion' },
    stability: { type: 'string', description: 'Voice stability, 0–1 (overrides the character\'s)' },
    similarity: { type: 'string', description: 'Voice similarity boost, 0–1 (overrides the character\'s)' },
    json: { type: 'boolean', default: false, description: 'Print the report as JSON' },
    dir: dirArg,
  },
  async run({ args }) {
    await guard('swap', async () => {
      const apiKey = elevenLabsApiKeyFromEnv() ?? '';
      if (!apiKey) throw new Error('Set ELEVENLABS_API_KEY (or ELEVEN_LABS_KEY).');
      const target = await swapTarget(args.voice, charactersDir({ dir: args.dir }), new ElevenLabsVoiceCatalog(apiKey));
      const num = (value: string | undefined, name: string) => {
        if (value === undefined) return undefined;
        const n = Number(value);
        if (!Number.isFinite(n) || n < 0 || n > 1) throw new Error(`--${name} must be from 0 to 1.`);
        return n;
      };
      const settings = { ...target.settings };
      const stability = num(args.stability, 'stability');
      const similarity = num(args.similarity, 'similarity');
      if (stability !== undefined) settings.stability = stability;
      if (similarity !== undefined) settings.similarity_boost = similarity;
      const seed = args.seed === undefined ? undefined : Number(args.seed);
      const report = await swapVoice({
        video: args.video,
        out: args.out,
        apiKey,
        voice: { id: target.id, name: target.character ? `${target.name} (${target.character})` : target.name },
        model: args.model,
        settings,
        removeBackgroundNoise: !args['keep-noise'],
        seed,
        text: args.text,
        aligner: args.text ? ElevenLabsAligner.fromEnv() : undefined,
      });
      if (args.json) console.log(JSON.stringify(report, null, 2));
      else console.log(`${formatSwap(report)}\nWrote ${shown(report.out)}, ${shown(`${swapStem(report.out)}.swap.json`)}`);
    });
  },
});

